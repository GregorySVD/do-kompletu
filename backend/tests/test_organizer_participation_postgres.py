def test_postgres_creation_is_atomic_and_uncommitted_activity_is_not_visible(
    pg_engine, organizers_pg
):
    _, users, _ = organizers_pg
    observed = []

    def observe(_mapper, connection, target):
        assert (
            connection.scalar(
                select(Activity.id).where(Activity.id == target.activity_id)
            )
            == target.activity_id
        )
        with pg_engine.connect() as other:
            assert (
                other.scalar(
                    select(Activity.id).where(Activity.id == target.activity_id)
                )
                is None
            )
            assert (
                other.scalar(
                    select(func.count())
                    .select_from(ActivityParticipation)
                    .where(ActivityParticipation.activity_id == target.activity_id)
                )
                == 0
            )
        observed.append(target.activity_id)

    event.listen(ActivityParticipation, "before_insert", observe)
    try:
        with Session(pg_engine) as session:
            result = activities.create_activity(
                session, activity_payload(), session.get(User, users[0])
            )
            activity_id = result.activity.id
    finally:
        event.remove(ActivityParticipation, "before_insert", observe)
    assert observed == [activity_id]
    with Session(pg_engine) as session:
        row = session.get(ActivityParticipation, (activity_id, users[0]))
        assert session.get(Activity, activity_id) is not None
        assert row.status == "CONFIRMED"
        assert row.joined_at == row.confirmed_at == NOW
        assert row.checked_in_at is None and row.completed_at is None
        body = activities.activity_to_read(
            activities.get_activity_by_id(
                session, activity_id, current_user_id=users[0]
            )
        )
        assert body.participant_count == body.available_slots == 1


def test_postgres_participation_failure_rolls_back_both_inserts(
    pg_engine, organizers_pg
):
    _, users, _ = organizers_pg
    attempted = []

    def fail(_mapper, connection, target):
        attempted.append(target.activity_id)
        assert (
            connection.scalar(
                select(Activity.id).where(Activity.id == target.activity_id)
            )
            == target.activity_id
        )
        # Force a real PostgreSQL INSERT/check-constraint failure rather than
        # raising before SQL executes. Activity was already flushed above.
        target.status = "INVALID_INSERT"

    event.listen(ActivityParticipation, "before_insert", fail)
    try:
        with Session(pg_engine) as session:
            with pytest.raises(IntegrityError) as caught:
                activities.create_activity(
                    session, activity_payload(), session.get(User, users[0])
                )
            assert caught.value.orig.sqlstate == "23514"
            assert not session.in_transaction()
    finally:
        event.remove(ActivityParticipation, "before_insert", fail)
    assert len(attempted) == 1
    with Session(pg_engine) as session:
        assert session.get(Activity, attempted[0]) is None
        assert session.get(ActivityParticipation, (attempted[0], users[0])) is None


def test_postgres_organizer_duplicate_is_rejected_by_existing_primary_key(
    pg_engine, organizers_pg
):
    activity_id, users, _ = organizers_pg
    with Session(pg_engine) as session:
        with pytest.raises(IntegrityError) as caught, session.begin_nested():
            session.execute(
                insert(ActivityParticipation).values(
                    activity_id=activity_id,
                    user_id=users[0],
                    status="CONFIRMED",
                    joined_at=NOW,
                    confirmed_at=NOW,
                )
            )
        assert caught.value.orig.sqlstate == "23505"
        assert caught.value.orig.diag.constraint_name == "pk_activity_participations"
        assert (
            session.scalar(
                select(func.count())
                .select_from(ActivityParticipation)
                .where(ActivityParticipation.activity_id == activity_id)
            )
            == 1
        )


@pytest.mark.parametrize(
    "coordinates,error",
    [
        (AT_VENUE, None),
        (
            ActivityCheckIn(latitude=0, longitude=0, accuracy_m=20),
            "Outside check-in radius",
        ),
        (
            ActivityCheckIn(latitude=52.4232, longitude=16.9461, accuracy_m=101),
            "Location accuracy is insufficient for check-in",
        ),
    ],
)
def test_postgres_organizer_obeys_real_postgis_and_accuracy(
    pg_engine, organizers_pg, coordinates, error
):
    activity_id, users, _ = organizers_pg
    with Session(pg_engine) as session:
        if error:
            with pytest.raises(participation.ParticipationError, match=error):
                participation.check_in_activity(
                    session, activity_id, users[0], coordinates
                )
        else:
            result = participation.check_in_activity(
                session, activity_id, users[0], coordinates
            )
            body = activities.activity_to_read(result)
            assert body.current_user_participation.status == "CHECKED_IN"
            assert body.checked_in_count == 1
            assert body.permissions.can_upload_photo
        row = session.get(ActivityParticipation, (activity_id, users[0]))
        assert row.status == ("CONFIRMED" if error else "CHECKED_IN")
        assert (row.checked_in_at is None) == bool(error)


def run_locked_pair(engine, activity_id, operation):
    """Observe both writers blocked in PostgreSQL before releasing the parent."""
    name = f"dk-organizer-lock-{uuid4().hex}"

    def worker(index):
        with Session(engine, expire_on_commit=False, autoflush=False) as session:
            session.execute(
                text("SELECT set_config('application_name', :name, true)"),
                {"name": name},
            )
            try:
                return operation(session, index)
            except (
                participation.ParticipationError,
                management.ActivityManagementError,
            ) as exc:
                return exc.status_code, str(exc)

    with Session(engine) as holder, ThreadPoolExecutor(max_workers=2) as executor:
        holder.scalar(
            select(Activity).where(Activity.id == activity_id).with_for_update()
        )
        futures = []
        try:
            for index in range(2):
                futures.append(executor.submit(worker, index))
                wait_for_lock_waiters(engine, name, index + 1)
        finally:
            holder.rollback()
        return [future.result(timeout=15) for future in futures]


def test_postgres_concurrent_joins_respect_organizer_capacity(pg_engine, organizers_pg):
    activity_id, users, _ = organizers_pg

    def join(session, index):
        body = activities.activity_to_read(
            participation.join_activity(session, activity_id, users[index + 1])
        )
        return body.current_user_participation.status

    results = run_locked_pair(pg_engine, activity_id, join)
    assert results == ["JOINED", "WAITLISTED"]
    with Session(pg_engine) as session:
        body = activities.activity_to_read(
            activities.get_activity_by_id(
                session, activity_id, current_user_id=users[0]
            )
        )
        assert body.participant_count == 2
        assert body.available_slots == 0 and body.waitlist_count == 1
        assert body.current_user_participation.status == "CONFIRMED"
        participation.leave_activity(session, activity_id, users[1])
        row = session.get(
            ActivityParticipation, (activity_id, users[2]), populate_existing=True
        )
        assert row.status == "JOINED"
        assert (
            session.get(ActivityParticipation, (activity_id, users[0])).status
            == "CONFIRMED"
        )


def test_postgres_concurrent_organizer_check_in_uses_parent_lock(
    pg_engine, organizers_pg
):
    activity_id, users, _ = organizers_pg

    def check_in(session, _index):
        participation.check_in_activity(session, activity_id, users[0], AT_VENUE)
        return 200

    results = run_locked_pair(pg_engine, activity_id, check_in)
    assert results == [200, (409, "Already checked in")]
    with Session(pg_engine) as session:
        row = session.get(ActivityParticipation, (activity_id, users[0]))
        assert row.status == "CHECKED_IN" and row.checked_in_at == NOW
        assert session.get(User, users[0]).points_total == 0


def test_postgres_legacy_overcapacity_retains_exact_count_and_waits_for_real_slot(
    pg_engine, organizers_pg
):
    activity_id, users, _ = organizers_pg
    with Session(pg_engine) as session:
        # Model the safe backfill outcome: preexisting external reservations
        # remain active even when adding the organizer exceeds the old maximum.
        session.add_all(
            ActivityParticipation(
                activity_id=activity_id, user_id=user_id, status="JOINED", joined_at=NOW
            )
            for user_id in users[1:3]
        )
        session.commit()
        result = participation.join_activity(session, activity_id, users[3])
        body = activities.activity_to_read(result)
        assert body.current_user_participation.status == "WAITLISTED"
        assert body.participant_count == 3 and body.max_participants == 2
        assert body.available_slots == 0 and body.waitlist_count == 1
        result = participation.leave_activity(session, activity_id, users[1])
        body = activities.activity_to_read(result)
        assert body.participant_count == 2 and body.waitlist_count == 1
        assert (
            session.get(ActivityParticipation, (activity_id, users[3])).status
            == "WAITLISTED"
        )
        result = participation.leave_activity(session, activity_id, users[2])
        body = activities.activity_to_read(result)
        assert body.participant_count == 2 and body.waitlist_count == 0
        assert (
            session.get(
                ActivityParticipation, (activity_id, users[3]), populate_existing=True
            ).status
            == "JOINED"
        )
        assert (
            session.get(ActivityParticipation, (activity_id, users[0])).status
            == "CONFIRMED"
        )


def test_postgres_concurrent_organizer_finalization_awards_ten_once(
    pg_engine, organizers_pg
):
    activity_id, users, clock = organizers_pg
    with Session(pg_engine) as session:
        participation.check_in_activity(session, activity_id, users[0], AT_VENUE)
    clock[0] = END

    def finalize(session, _index):
        management.finalize_activity(session, activity_id, users[0])
        return 200

    results = run_locked_pair(pg_engine, activity_id, finalize)
    assert results == [200, (409, "No unresolved attendance to finalize")]
    with Session(pg_engine) as session:
        row = session.get(ActivityParticipation, (activity_id, users[0]))
        assert row.status == "COMPLETED" and row.completed_at == END
        assert session.get(User, users[0]).points_total == 10
        with pytest.raises(management.ActivityManagementError, match="No unresolved"):
            management.finalize_activity(session, activity_id, users[0])
        assert session.get(User, users[0]).points_total == 10


def isolated_seed(organizer_id):
    source = (
        Path(__file__).resolve().parents[1] / "do_kompletu_seed_activities.sql"
    ).read_text(encoding="utf-8")
    ids = {}

    def unique_id(match):
        return str(ids.setdefault(match.group(), uuid4()))

    # Substitute only fixed identifiers/organizer selection for test isolation;
    # the seed's actual data-modifying CTE and conflict handling run unchanged.
    source = re.sub(r"11111111-1111-1111-1111-\d{12}", unique_id, source)
    source = source.replace(
        "WHERE is_active = TRUE",
        f"WHERE is_active = TRUE AND id = '{organizer_id}'::uuid",
    )
    assert ids, "The actual seed must contain its documented fixed UUIDs"
    return source, list(ids.values())


def test_postgres_sql_seed_creates_organizers_atomically_and_rerun_preserves_evidence(
    pg_engine, organizers_pg
):
    _, users, _ = organizers_pg
    source, seed_ids = isolated_seed(users[0])
    with pg_engine.connect() as connection:
        transaction = connection.begin()
        try:
            connection.exec_driver_sql(source)
            rows = (
                connection.execute(
                    select(ActivityParticipation).where(
                        ActivityParticipation.activity_id.in_(seed_ids)
                    )
                )
                .mappings()
                .all()
            )
            assert len(rows) == len(seed_ids)
            assert all(
                row["user_id"] == users[0]
                and row["status"] == "CONFIRMED"
                and row["joined_at"] == row["confirmed_at"]
                and row["checked_in_at"] is None
                for row in rows
            )
            # Real attendance and an existing legacy activity with no membership
            # must both remain untouched when the operator reruns the seed.
            connection.execute(
                ActivityParticipation.__table__.update()
                .where(ActivityParticipation.activity_id == seed_ids[0])
                .values(status="CHECKED_IN", checked_in_at=NOW)
            )
            connection.execute(
                delete(ActivityParticipation).where(
                    ActivityParticipation.activity_id == seed_ids[1]
                )
            )
            before = connection.execute(
                select(ActivityParticipation)
                .where(ActivityParticipation.activity_id.in_(seed_ids))
                .order_by(ActivityParticipation.activity_id)
            ).all()
            connection.exec_driver_sql(source)
            after = connection.execute(
                select(ActivityParticipation)
                .where(ActivityParticipation.activity_id.in_(seed_ids))
                .order_by(ActivityParticipation.activity_id)
            ).all()
            assert after == before
            assert connection.scalar(
                select(func.count())
                .select_from(Activity)
                .where(Activity.id.in_(seed_ids))
            ) == len(seed_ids)
        finally:
            transaction.rollback()


def test_postgres_sql_seed_participation_failure_rolls_back_created_activities(
    pg_engine, organizers_pg
):
    _, users, _ = organizers_pg
    source, seed_ids = isolated_seed(users[0])
    assert all(isinstance(value, UUID) for value in seed_ids)
    sql_ids = ", ".join(f"'{value}'::uuid" for value in seed_ids)
    trigger_name = f"organizer_seed_failure_{uuid4().hex}"
    with pg_engine.connect() as connection:
        transaction = connection.begin()
        try:
            connection.exec_driver_sql(
                "CREATE FUNCTION pg_temp.fail_organizer_seed() RETURNS trigger "
                "LANGUAGE plpgsql AS $$ BEGIN "
                "RAISE EXCEPTION 'forced seed organizer insertion failure'; END $$"
            )
            connection.exec_driver_sql(
                f"CREATE TRIGGER {trigger_name} BEFORE INSERT ON activity_participations "
                f"FOR EACH ROW WHEN (NEW.activity_id IN ({sql_ids})) "
                "EXECUTE FUNCTION pg_temp.fail_organizer_seed()"
            )
            with (
                pytest.raises(DBAPIError, match="forced seed organizer"),
                connection.begin_nested(),
            ):
                connection.exec_driver_sql(source)
            assert (
                connection.scalar(
                    select(func.count())
                    .select_from(Activity)
                    .where(Activity.id.in_(seed_ids))
                )
                == 0
            )
            assert (
                connection.scalar(
                    select(func.count())
                    .select_from(ActivityParticipation)
                    .where(ActivityParticipation.activity_id.in_(seed_ids))
                )
                == 0
            )
        finally:
            transaction.rollback()
